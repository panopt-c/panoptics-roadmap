def _check_body(body):
    if not isinstance(body, str):
        return f"body must be a JSON string, got {type(body).__name__}. Serialize it with json.dumps(...)"
    try:
        data = json.loads(body)
    except ValueError:
        return "body is not valid JSON"
    if not isinstance(data, dict):
        return "body must be a JSON object"
    if not isinstance(data.get("model"), str) or not data["model"].strip():
        return "model: a non-empty string is required"
    tokens = data.get("max_tokens")
    if isinstance(tokens, bool) or not isinstance(tokens, int) or tokens < 1:
        return "max_tokens: a positive integer is required"
    if "system" in data and not isinstance(data["system"], str):
        return "system: must be a string"
    messages = data.get("messages")
    if not isinstance(messages, list) or not messages:
        return "messages: a non-empty list is required"
    for i, message in enumerate(messages):
        if not isinstance(message, dict) or set(message) != {"role", "content"}:
            return f"messages.{i}: each message needs exactly the keys 'role' and 'content'"
