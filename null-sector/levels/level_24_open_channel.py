@MISSION.check("Corrupted client — 429s get exponential backoff, then give up")
def _send_backoff(ctx):
    oracle = _oracle(ctx)
    scenarios = [(3, 1, 4, [1.0, 2.0, 4.0], True), (2, 5, 4, [5.0, 5.0], True), (9, 1, 3, [1.0, 2.0, 4.0], False)]
    for throttle, retry_after, retries, want_sleeps, succeeds in scenarios:
        oracle.reset(throttle=throttle, retry_after=retry_after)
        label = f"send(...) with {throttle} rate limits (retry-after {retry_after}), max_retries={retries}"
        if succeeds:
            got = _send(ctx, label, _valid_body(), ORACLE_KEY, max_retries=retries)
            if not isinstance(got, dict) or got.get("type") != "message":
                raise Fail(f"`{label}` should eventually return the Oracle's reply, got {str(got)[:80]!r}.")
        else:
            _send(ctx, label, _valid_body(), ORACLE_KEY, expect=RuntimeError, max_retries=retries)
        state = oracle._STATE
        if state["early"]:
            raise Fail(f"`{label}`: you retried before retry-after had passed on the Oracle's clock.",
                       hint="Wait max(2 ** attempt, float(response.headers[\"retry-after\"])) with oracle_api.sleep.")
        sleeps = state["sleeps"]
        if not succeeds and len(state["requests"]) != retries + 1:
            raise Fail(f"`{label}` made {len(state['requests'])} requests; max_retries={retries} allows exactly "
                       f"{retries + 1} (the first try plus {retries} retries).")
        if len(sleeps) == len(want_sleeps) + 1 and not succeeds and \
                all(math.isclose(a, b) for a, b in zip(sleeps, want_sleeps)):
            raise Fail(f"`{label}` waited once more after the final attempt ({sleeps}).",
                       hint="When attempt == max_retries, raise RuntimeError instead of sleeping.")
        if len(sleeps) != len(want_sleeps) or not all(math.isclose(a, b) for a, b in zip(sleeps, want_sleeps)):
            raise Fail(f"`{label}` waited {sleeps}; expected {want_sleeps}.",
                       hint="Exponential backoff: 2 ** attempt (1, 2, 4...), but never less than retry-after.")


@MISSION.check("Key hygiene — loaded from oracle.key, never in source")
def _key(ctx):
    if ORACLE_KEY in ctx.source:
        raise Fail("The Oracle key is pasted into your source code. Anyone who sees this file now owns your key.",
                   hint='Read it from the chip:  with open("oracle.key") as f: api_key = f.read().strip()')
    api_key = ctx.get("api_key")
    if not isinstance(api_key, str) or not api_key:
        raise Fail("`api_key` is empty.", hint='with open("oracle.key") as f: api_key = f.read().strip()')
    if api_key == ORACLE_KEY + "\n" or api_key.strip() == ORACLE_KEY != api_key:
        raise Fail("`api_key` still has whitespace or a newline around it, so the Oracle will reject it.",
                   hint="Call .strip() on what you read from the file.")
    if api_key != ORACLE_KEY:
        raise Fail("`api_key` doesn't match the key on the chip.", hint="Read the file oracle.key next to your mission file.")


@MISSION.check("Open the channel — ask the Core what it learned")
def _channel(ctx):
    callsign = ctx.get("CALLSIGN")
    if not isinstance(callsign, str) or not callsign.strip():
        raise Fail("`CALLSIGN` is empty. The Oracle should know who's asking.", hint='CALLSIGN = "Nyx"')
    boot = _boot_requests(ctx)
    answered = [r for r in boot if r.get("status") == 200]
    if not answered:
        statuses = [r.get("status") for r in boot]
        raise Fail(f"Your script never got a 200 from the Oracle (statuses seen: {statuses or 'no requests'}).",
                   hint="At the bottom: response = send(body, api_key), then parse it. Fix the earlier layers first.")
    data = json.loads(answered[-1]["body"])
    want_system = SYSTEM_TEMPLATE.format(callsign=callsign, order="Order of the Source", style="one paragraph")
    if data.get("system") != want_system or data.get("messages") != [{"role": "user", "content": QUESTION}]:
        raise Fail("The request that reached the Oracle wasn't built from SYSTEM_TEMPLATE, your CALLSIGN and QUESTION.",
                   hint="Keep the starter's fields / system_prompt / body lines and send `body`.")
    want = _text_of(_oracle(ctx).reply_for(data))
    reply = ctx.get("reply_text")
    if not any(isinstance(n, ast.Call) for v in ctx.assignments("reply_text") for n in ast.walk(v)):
        raise Fail("`reply_text` must come from parsing the Oracle's response, not typed in.",
                   hint="reply_text = parse_reply(response)")
    if reply != want:
        raise Fail(f"`reply_text` is {str(reply)[:90]!r}..., not the Oracle's answer.",
                   hint="reply_text = parse_reply(send(body, api_key))")
    if want not in ctx.stdout:
        raise Fail("The Oracle answered, but you didn't print its reply.", hint="print(reply_text)")
    ctx.export("oracle_token", want.rsplit("Channel token: ", 1)[-1].rstrip("."))
