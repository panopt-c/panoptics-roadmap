            if isinstance(got, str) and "..." in got and "..." not in want:
                hint = "A thinking block leaked into the answer. Filter by block[\"type\"] == \"text\"."
            raise Fail(f"`{label}` returned {got!r}, expected {want!r}.", hint=hint)


