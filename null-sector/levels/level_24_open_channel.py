def _handle(path, headers, body):
    if path != ENDPOINT:
        return _error(404, "not_found_error", f"no such endpoint: {path!r} (try {ENDPOINT!r})")
    if not isinstance(headers, dict):
        return _error(400, "invalid_request_error", "headers must be a dict")
    lower = {str(k).lower(): v for k, v in headers.items()}
    key = lower.get("x-api-key")
    if not isinstance(key, str) or hashlib.sha256(key.encode()).hexdigest() != _KEY_SHA256:
        return _error(401, "authentication_error", "invalid x-api-key")
    if lower.get("anthropic-version") != API_VERSION:
        return _error(400, "invalid_request_error", f"anthropic-version header must be {API_VERSION!r}")
    if lower.get("content-type") != "application/json":
        return _error(400, "invalid_request_error", "content-type header must be 'application/json'")
    if _STATE["clock"] < _STATE["blocked_until"]:
        _STATE["early"] += 1
        wait = _STATE["blocked_until"] - _STATE["clock"]
        return _error(429, "rate_limit_error", "retried too early: respect retry-after",
                      {"retry-after": str(max(1, int(wait + 0.999)))})
    if _STATE["throttle"] > 0:
        _STATE["throttle"] -= 1
        _STATE["blocked_until"] = _STATE["clock"] + _STATE["retry_after"]
        return _error(429, "rate_limit_error", "rate limited: too many requests",
                      {"retry-after": str(_STATE["retry_after"])})
    data = _check_body(body)
    if isinstance(data, str):
        return _error(400, "invalid_request_error", data)
    return Response(200, reply_for(data), {"request-id": "req_" + str(len(_STATE["history"]))})


